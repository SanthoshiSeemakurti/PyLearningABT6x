"""
Tuple in python
Tuple  is a collection of ordered and immutable (unchangeable) items.
    ordered - elements have a fixed position
    immutable - cannot be changed after creation
    allows duplicates
"""
my_tuple = (1,2,"sing",4.5)
print(my_tuple)
# my_tuple[0] = "hi" # TypeError: 'tuple' object does not support item assignment

single = (3,)       # here "," is mandatory
print(single)
print(type(single))

